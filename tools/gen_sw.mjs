// Regenerates sw.js with the full list of files to precache and a fresh
// cache version, so an updated game replaces the old one on next launch.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
const root = new URL('..', import.meta.url).pathname;
const files = [];
function walk(d) {
  for (const f of readdirSync(join(root, d))) {
    const p = join(d, f);
    if (statSync(join(root, p)).isDirectory()) walk(p);
    else if (/\.(js|css|png|webmanifest|html|svg)$/.test(f)) files.push('./' + p.replace(/\\/g, '/'));
  }
}
walk('src'); walk('icons');
files.push('./index.html', './manifest.webmanifest', './');
const h = createHash('sha1');
for (const f of files) if (f !== './') h.update(readFileSync(join(root, f)));
const ver = h.digest('hex').slice(0, 10);
const tpl = `/* TOUCHLINE 26 service worker (generated by tools/gen_sw.mjs) */
const CACHE = 't26-${ver}';
const ASSETS = ${JSON.stringify(files.sort(), null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE)
    .then((c) => Promise.allSettled(ASSETS.map((a) => c.add(new Request(a, { cache: 'reload' })))))
    .then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  // cache first (instant, offline), refreshed in the background
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => {
    const net = fetch(req).then((res) => {
      if (res && res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => hit || caches.match('./index.html'));
    return hit || net;
  }));
});
`;
writeFileSync(join(root, 'sw.js'), tpl);
console.log('sw.js:', files.length, 'files, cache', ver);
