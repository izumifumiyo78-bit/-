/** Generate a name for a nationality. Returns { fn, ln, full, short }. */
export function makeName(rng, nat) {
  const pool = POOLS[(NATIONS[nat] || NATIONS.ENG).c] || POOLS.en;
  if (pool.mono && rng() < 0.18) {
    const m = pool.mono[Math.floor(rng() * pool.mono.length)];
    return { fn: '', ln: m };
  }
  const fn = pool.first[Math.floor(rng() * pool.first.length)];
  const ln = pool.last[Math.floor(rng() * pool.last.length)];
  return { fn, ln };
}
export function fullName(p) {
  if (!p.fn) return p.ln;
  const pool = POOLS[(NATIONS[p.nat] || NATIONS.ENG).c] || POOLS.en;
  return pool.surFirst ? `${p.ln} ${p.fn}` : `${p.fn}・${p.ln}`;
}
export function shortName(p) { return p.ln; }

// --- manager / staff names ------------------------------------------------------
export function makeManagerName(rng, nat) {
  const n = makeName(rng, nat);
  return fullName({ ...n, nat });
}
